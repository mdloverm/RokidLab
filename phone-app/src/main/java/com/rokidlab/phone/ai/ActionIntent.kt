package com.rokidlab.phone.ai

/**
 * 「用户这条消息是不是在**要求动手改东西**」（2026-10-09，P0-6 第 2 条）。
 *
 * ## 用途
 *
 * 收尾前做一次「诉求—动作」对齐：用户要的是"改"，而 agent 本轮**一个动作类工具都没调**，
 * 那就是典型的**假成功** —— 它读了一圈、说了几句话，任务一步没推进。
 * 真机证据（gps-live）：用户说"修"「重写」「继续」，T2~T7 共 **37 次工具调用、0 次写操作**，
 * 而现有自省只认"工具抛异常"，全程无异常 ⇒ 它一次都没触发。
 *
 * ## 判据为什么必须保守（宁可漏放）
 *
 * 误判的代价不对称：
 *  - **漏放**（该触发没触发）= 保持现状，最多少一次自纠机会；
 *  - **误放**（不该触发却触发）= 用户只是问个问题，却被框架打断、被迫再花一轮 ——
 *    这会让正常问答变得拖沓，比漏放更烦人。
 *
 * 所以判据是**白名单词组**（不是单字），且只认高置信的动作说法：
 * 用 `重写/改成/删掉/生成` 这类**两字以上**的词，不用 `写/改/加` 这类单字
 * （单字会命中"描写""抄写""改写历史"等无关语境）。
 */
object ActionIntent {

    /**
     * 高置信动作意图词（两字及以上，避免单字误伤）。
     *
     * 分组只是为了可读性，判定时一视同仁。
     */
    private val ACTION_PHRASES = listOf(
        // 修改现有产物
        "修改", "改一下", "改下", "改一改", "改成", "改个", "改掉", "改动",
        "调整", "优化", "重写", "重做", "重新写", "重新做", "换个", "换成", "替换",
        "加上", "加个", "增加", "去掉", "删掉", "删除", "移除", "补充",
        // 创建新产物
        "生成", "创建", "新建", "做一个", "做个", "写一个", "写个", "画一个", "画个",
        "帮我做", "帮我写", "帮我生成", "帮我改", "帮我加",
        // 装机 / 部署类
        "安装", "装上", "装到", "卸载", "部署", "打包",
        // 修复类
        "修复", "修一下", "修下", "修好", "弄好", "搞定它", "处理一下",
        // 续做类（★ 真机原话：gps-live 案 T6/T7 都是「继续」，前面已经干了一堆活但零产出，
        // 此时"继续"就是"接着把活干完" —— 必须和"重写"同判据，否则漏放它等于放过最常见的空转轮）
        "继续", "接着", "往下做", "接着做", "继续做", "再来一次", "再试一次",
    )

    /**
     * 否定/疑问语境：出现这些说明用户在**问**而不是在**要求改**，
     * 或者已经明确说"先别动"。命中即不视为动作请求（保守）。
     */
    private val NEGATIVE_HINTS = listOf(
        "为什么", "怎么会", "是什么原因", "什么意思", "解释一下", "讲讲", "说说",
        "先别", "不要改", "别动", "先不改", "暂时不",
    )

    /** 输入长度上限：超长多半是粘贴的任务描述，交给模型自己判断即可（不在此处插手） */
    private const val MAX_LEN = 100

    /**
     * 这条用户消息是否在要求"动手改"。
     *
     * @param text 用户本轮原话
     */
    fun looksLikeActionRequest(text: String?): Boolean {
        val t = text?.trim().orEmpty()
        if (t.isEmpty() || t.length > MAX_LEN) return false
        if (t.contains('\n') || t.contains('\r')) return false
        val lower = t.lowercase()
        if (NEGATIVE_HINTS.any { lower.contains(it) }) return false
        return ACTION_PHRASES.any { lower.contains(it) }
    }
}
