package com.rokidlab.phone.ai

/**
 * 失败教训的**文案**（框架自产，纯函数）。
 *
 * ## 为什么要抽出来
 * 2026-10-07 审计发现一处真实高危：工具失败后自动沉淀教训时，
 * 有一处把**工具原始输出** `raw` 写进了长期记忆库，而教训库每轮都会注入提示词、
 * 且注入时的尾句是指令性的「做同类事情时按它来」（`OpenAiService.buildSystemMessage`）。
 *
 * 而 `raw` 对 `fetch_webpage` / `search_web` 这类工具**整段可能来自攻击者控制的网页正文**
 * ⇒ 攻击者只需构造一个让工具失败的页面，就能写下一条**持久生效的指令**，
 * 且**不需要接触这台设备**。
 *
 * 修法是「只写框架自产的确定性文案」，而这条文案就是本类的全部内容——
 * 把它做成纯函数，才能用单测钉住「**绝不包含任何工具输出**」这个不变量。
 */
object LessonText {

    /**
     * 一条"该工具在这台设备上失败过"的教训文案。
     *
     * ⚠️ **参数里刻意没有任何工具输出/异常消息** —— 这是本类的核心不变量。
     * 早期实现在这里拼 `lastError.message.take(60)` 与 `raw.take(200)`，
     * 等于把不可信原文写进长期记忆；现已全部移除。
     *
     * @param toolName 工具名（**工具名本身是可信的**：它来自本进程注册表，不是外部内容）
     */
    fun toolFailed(toolName: String): String =
        "工具 $toolName 在这台设备上失败过：原样重试无效。" +
            "下次先确认前置条件（连接/权限/参数/环境是否就绪），" +
            "或换用其它工具与思路；确认此条不再成立时可用 manage_memory 删除。"

    /**
     * 构造给**模型**看的失败反思引导（不是教训库内容，只回填给本轮）。
     *
     * 与 [toolFailed] 的区别：这段**不进长期库**，所以可以引用本轮的具体错误串
     * ——它只出现在模型当前这一轮的上下文里。
     */
    fun retryGuidance(errorMessage: String?): String {
        val brief = errorMessage?.replace(Regex("\\s+"), " ")?.trim().orEmpty()
        val because = if (brief.isEmpty()) "" else "：$brief"
        return "工具执行失败$because。请先分析失败原因再决定下一步：" +
            "参数是否正确？是否换用其他工具或参数？是否把任务拆小？" +
            "不要原样重复刚才的调用；若换一种方式仍无法完成，请如实告知用户。"
    }
}