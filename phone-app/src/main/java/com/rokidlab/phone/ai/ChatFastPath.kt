package com.rokidlab.phone.ai

/**
 * 「闲聊快路」的装配判定（2026-09-29，结构性省 token 的第一刀）。
 *
 * ## 存在的理由
 *
 * 主 Agent 每轮全量下发 ~83 个工具 Schema（≈ 1.5~2.5 万 input token），哪怕用户只是说了句
 * 「你好」也要付全价 —— 这是闲聊场景的成本大头。DeepSeek 有自动前缀缓存能救回大部分，
 * 但方舟等其他端点没有同等缓存，每一轮都是全价。而纯闲聊（问候/感谢/敷衍应答/常识问答/创作）
 * 恰恰**一个工具都不需要**。
 *
 * ## 机制（两个组件，缺一不可）
 *
 *  1. [isPureChat]：高置信纯闲聊判定 → 该轮**不装配任何工具**，人设换精简版
 *     （`OpenAiService.buildChatOnlySystemMessage`），并明确告知模型本轮无工具；
 *  2. [NEED_TOOLS_MARKER] 逃生舱：模型若发现用户的问题**必须**有工具才能正确回答，
 *     按约定只回复一行 `[NEED_TOOLS]` —— 主循环检测到后自动挂载全量工具、重建请求原地重来
 *     （探测轮成本 ≈ 千级 token，误判的代价是一次小幅重试，而不是能力缺失或编造）。
 *
 * ## 设计取舍：宁可漏放、不可误放
 *
 * [isPureChat] 只认**高置信**模式（问候/感谢/告别/短应答/少量纯聊天固定句式），
 * 任何含工具意图线索（时间/设备/搜索/文件/播放…）、URL、多行文本的一律**不进快路**
 * —— 漏放的代价只是"这轮多花两万 token"（维持原状），误放的代价是能力缺失或模型编造。
 * 判据是**白名单**而不是黑名单，就是这个原因。
 */
internal object ChatFastPath {

    /** 探测轮的逃生舱标记：模型需要工具时按约定只回复这一行（见类注释的机制说明） */
    const val NEED_TOOLS_MARKER = "[NEED_TOOLS]"

    /** 快路轮输入长度上限：长文本多半是任务描述/粘贴内容，绝不进快路 */
    private const val MAX_LEN = 64

    /** 句尾允许拖的标点/语气词（「多谢啦」「好无聊啊」「讲个笑话吧」都算纯闲聊收尾） */
    private const val TAIL = "[!！?？。~～。，,\\s啊呀哦呢叭吧啦]*"

    /**
     * 高置信纯闲聊模式（白名单）。整条消息（去首尾空白、忽略大小写）必须完整命中其中之一。
     */
    private val CHAT_PATTERNS = listOf(
        // 问候 / 唤起
        Regex("^(你好|您好|哈喽|哈罗|嗨|hi|hello|hey|在吗|在么|在不在)$TAIL", RegexOption.IGNORE_CASE),
        // 时段问候
        Regex("^(早上好|早安|上午好|中午好|下午好|晚上好|晚安|好梦|午安)$TAIL"),
        // 感谢 / 客套
        Regex("^(谢谢|谢谢啦|多谢|感谢|感谢感谢|辛苦了|辛苦啦|麻烦你了|麻烦啦|你真好|你真棒)$TAIL"),
        // 告别
        Regex("^(再见|拜拜|白白|下次见|回见|我走了|我先走了|不打扰了)$TAIL"),
        // 敷衍应答 / 语气词（纯 backchannel，无任何任务语义）
        Regex("^(嗯+|嗯嗯|哦+|噢+|喔+|好滴|好的|好嘞|好呀|好啊|好吧|行吧|可以|没问题|收到|明白|了解了|知道了|知道啦|懂了|ok|okay)$TAIL", RegexOption.IGNORE_CASE),
        // 笑 / 情绪反应
        Regex("^(哈哈+|嘿嘿+|嘻嘻+|呵呵+|233+|666+|wow|哇|哇塞)$TAIL", RegexOption.IGNORE_CASE),
        // 亲昵 / 陪伴（陪伴场景就是纯对话）
        Regex("^(爱你|喜欢你|想你了|抱抱|比心|陪我聊聊天|陪我聊聊|陪我玩|无聊啊|好无聊|我回来了)$TAIL"),
        // 身份 / 能力问答（参数化知识足以回答，不需要工具）
        Regex("^(你是谁|你叫什么名字?|你是机器人吗|你是人吗|你是什么|自我介绍[一下]+|你会什么|你能做什么|你会做什么)[?？!！。~～。，,\\s]*$"),
        // 轻创作请求（模型直接输出，不依赖任何外部数据）
        Regex("^(讲个笑话|说个笑话|来个笑话|讲个冷笑话|说个冷笑话|说个谜语|出个谜语|夸夸我|安慰一下我|哄哄我|给我加油)$TAIL"),
    )

    /**
     * 工具意图线索（黑名单复核）：白名单之外的句子一律不进快路，这里只负责把
     * "看着像问候但实际要动手"的边缘情况再挡一道（如「早上好，今天天气怎么样」）。
     */
    private val TOOL_HINTS = listOf(
        "几点", "时间", "日期", "几号", "星期", "礼拜", "天气", "气温", "温度", "下雨",
        "提醒", "闹钟", "定时", "倒计时", "日历", "日程", "会议",
        "打电话", "拨打", "拨号", "短信", "微信", "qq",
        "播放", "放一首", "来一首", "唱歌", "音乐", "歌曲", "暂停", "下一首", "上一首", "歌词",
        "音量", "亮度", "静音", "蓝牙", "wifi", "热点", "电量", "电池", "充电",
        "截图", "截屏", "拍照", "拍一张", "看看", "看一下", "眼镜",
        "打开", "启动", "安装", "卸载", "应用", "app",
        "搜索", "搜一下", "搜个", "查一下", "查个", "查询", "查查", "帮我查",
        "新闻", "资讯", "股价", "汇率", "基金", "股票",
        "文件", "保存", "生成", "写一个", "写个", "代码", "翻译成", "翻译为", "朗读",
        "http", "www.", ".com", ".cn", ".html",
    )

    /** 是否进快路（不装配工具）。判据见类注释：白名单 + 黑名单复核，宁可漏放。 */
    fun isPureChat(text: String): Boolean {
        val t = text.trim()
        if (t.isEmpty() || t.length > MAX_LEN) return false
        // 多行/含换行：多半是粘贴的任务描述，不进快路
        if (t.contains('\n') || t.contains('\r')) return false
        val lower = t.lowercase()
        if (TOOL_HINTS.any { lower.contains(it) }) return false
        return CHAT_PATTERNS.any { it.matches(t) }
    }

    /**
     * 探测轮回复是否为「需要工具」的升级信号。
     *
     * 宽进：标记出现在短回复的任意位置都算（模型可能带个前缀），大小写不敏感；
     * 长度上限 200 是防误伤 —— 正常闲聊回复不会恰好包含这个标记，
     * 用户故意问「[NEED_TOOLS] 是什么」时的长回答也不会触发。
     */
    fun needsUpgrade(content: String?): Boolean {
        val c = content?.trim().orEmpty()
        if (c.isEmpty() || c.length > 200) return false
        return c.lowercase().contains(NEED_TOOLS_MARKER.lowercase())
    }
}
